// build-choir-sfz.mjs — generate vendor/sfz/gen/choir-{male,female,mixed}.sfz
// from the SSO chorus (Sonatina Symphonic Orchestra v4, CC Sampling Plus 1.0,
// github.com/peastman/sso — vendored to vendor/sfz/SSO-Chorus/ this round).
//
// The shipped "Mixed Chorus.sfz" carries per-note loop points and tune
// corrections worth preserving, but references ..\Samples-looped\Chorus\ with
// backslashes; this rewrites paths to the vendored layout and splits the
// male (G2-F#4) and female (G4-C6) sample sets into their own instruments so
// a line never crosses the gender seam mid-phrase (research/choir-research.md
// §4 "register honesty").
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'vendor/sfz/SSO-Chorus/Mixed Chorus.sfz');
const OUT = join(ROOT, 'vendor/sfz/gen');

const src = readFileSync(SRC, 'utf8');
const header = src.slice(src.indexOf('<group>'), src.indexOf('<region>')).trim();
const regions = src.split('<region>').slice(1).map((r) => '<region>\n' + r.trim().replace(/sample=\.\.\\Samples-looped\\Chorus\\/, 'sample=../SSO-Chorus/Samples/'));
const male = regions.filter((r) => r.includes('chorus-male'));
const female = regions.filter((r) => r.includes('chorus-female'));
if (!male.length || !female.length) throw new Error(`split failed: ${male.length} male / ${female.length} female regions`);

const emit = (name, regs) => {
  const body = `// GENERATED by scripts/build-choir-sfz.mjs from SSO Mixed Chorus.sfz — do not edit.\n// SSO chorus aahs (CC Sampling Plus 1.0, Mattias Westlund / peastman).\n\n${header}\n\n${regs.join('\n\n')}\n`;
  writeFileSync(join(OUT, name), body);
  console.log(`wrote vendor/sfz/gen/${name} — ${regs.length} regions`);
};
emit('choir-male.sfz', male);
emit('choir-female.sfz', female);
emit('choir-mixed.sfz', regions);
