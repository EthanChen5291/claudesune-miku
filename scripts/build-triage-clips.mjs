// Builds audition/triage-clips.js — the reference-audio pack for the r15
// ear-test page (audition/triage.html).
//
// Same hosting trick as audition/sample-pack.js (D93): file:// cannot fetch,
// so the audio ships as mp3 data-URIs in a sibling script tag that sets a
// global. Unlike sample-pack.js this file is NOT committed — the BRR decodes
// are rips of copyrighted game audio (see the brr-licensing card), so they
// stay local until Ethan rules on it. audition/triage-clips.js is gitignored.
//
// Usage: node scripts/build-triage-clips.mjs [--src <scratchdir>]
// The source wavs live in the r15 scratchpad (brr-nsmb/, brr-scary/, and the
// Battle Cats rip); pass --src to point at a different copy.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'audition/triage-clips.js');

const srcArg = process.argv.indexOf('--src');
const SRC = srcArg > -1 ? process.argv[srcArg + 1] : join(
  '/private/tmp/claude-501/-Users-ethanchen-Documents-GitHub-motif-engine',
  '7c400b2d-0406-4e06-b7a6-74d15ba16673/scratchpad/r15');

/** clip id -> the files that play under it, in order, with a spoken label */
const CLIPS = {
  // the sample-question clips: short one-shots, played as a labelled row
  nsmb_perc: [
    { file: 'brr-nsmb/Low Drum.wav', label: 'Low Drum (the doum, ~94Hz)' },
    { file: 'brr-nsmb/Tabla.wav', label: 'Tabla (the tak)' },
  ],
  nsmb_voices: [
    { file: 'brr-nsmb/Sitar.wav', label: 'Sitar (f5 pluck, jawari buzz)' },
    { file: 'brr-nsmb/Bah.wav', label: 'Bah (the NSMB shout stab, e5)' },
    { file: 'brr-nsmb/Kalimba.wav', label: 'Kalimba (c4, glides ~70 cents)' },
  ],
  scary_voices: [
    { file: 'brr-scary/Laugh.wav', label: 'Laugh (witch cackle)' },
    { file: 'brr-scary/AngelicalChoir.wav', label: 'Angelical Choir (non-harmonic shimmer)' },
    { file: 'brr-scary/DistortedGuitar2.wav', label: 'Distorted Guitar 2 (the low chug)' },
    { file: 'brr-scary/DistortedGuitar4.wav', label: 'Distorted Guitar 4 (mid stab)' },
  ],
  // the reference-track clip: trimmed, because the whole rip is 17MB of wav
  battlecats: [
    { file: 'battlecats_jungle.wav', label: 'Battle Cats jungle (0:00–0:40)', trim: ['-ss', '0', '-t', '40'] },
  ],
};

const has = (bin) => { try { execFileSync('which', [bin], { stdio: 'pipe' }); return true; } catch { return false; } };
if (!has('ffmpeg')) { console.error('ffmpeg is required (brew install ffmpeg)'); process.exit(1); }

const tmp = mkdtempSync(join(tmpdir(), 'triage-clips-'));
const out = {};
let bytes = 0, made = 0, missing = [];

for (const [clipId, entries] of Object.entries(CLIPS)) {
  const rows = [];
  for (const e of entries) {
    const src = join(SRC, e.file);
    if (!existsSync(src)) { missing.push(e.file); continue; }
    const mp3 = join(tmp, `${made++}.mp3`);
    // 96k mono keeps a 40s reference well under a megabyte; the one-shots are
    // tens of milliseconds, so bitrate barely matters for them. -af apad+
    // afade cleans the abrupt loop-chunk ends the BRR decode left behind.
    execFileSync('ffmpeg', [
      '-y', '-loglevel', 'error',
      ...(e.trim ?? []), '-i', src,
      '-ac', '1', '-b:a', '96k',
      '-af', 'highpass=f=20,afade=t=out:st=0:d=0.004:curve=exp,apad=pad_dur=0.01',
      ...(e.trim ? [] : ['-t', '2']),
      mp3,
    ], { stdio: 'pipe' });
    const b64 = readFileSync(mp3).toString('base64');
    bytes += b64.length;
    rows.push({ label: e.label, src: `data:audio/mpeg;base64,${b64}` });
  }
  if (rows.length) out[clipId] = rows;
}

rmSync(tmp, { recursive: true, force: true });

writeFileSync(OUT, `// GENERATED by scripts/build-triage-clips.mjs — do not edit, do not commit.\n`
  + `// Reference audio for audition/triage.html. Rips of copyrighted game audio:\n`
  + `// local-only until the brr-licensing question is answered.\n`
  + `window.TRIAGE_CLIPS = ${JSON.stringify(out)};\n`);

console.log(`wrote ${OUT}`);
console.log(`  ${Object.keys(out).length} clips, ${made} files, ${(bytes / 1e6).toFixed(2)}MB of base64`);
if (missing.length) console.log(`  MISSING (skipped): ${missing.join(', ')}`);
