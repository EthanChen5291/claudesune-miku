export function labelFor(filename) {
  const f = filename.toLowerCase();
  for (const [re, song, lane, emotion, energy] of LABEL_RULES) {
    if (re.test(f)) return { song, lane, emotion, energy, inferred: false };
  }
  return null;
}

/** tags the pack encodes in its filenames */
export function tagsFor(filename) {
  const f = filename.toLowerCase();
  const tags = [];
  if (/hands are divide/.test(f)) tags.push('hands_divided');
  if (/\(advanced\)|\(hard/.test(f)) tags.push('advanced');
  if (/\(simple\)|\(beginner\)|easy/.test(f)) tags.push('easy');
  if (/pianoitall/.test(f)) tags.push('pianoitall');
  if (/rousseau/.test(f)) tags.push('rousseau');
  if (/atlantic lights/.test(f)) tags.push('atlantic_lights');
  if (/midicollection/.test(f)) tags.push('midicollection');
  if (/full midi|midi file -/.test(f)) tags.push('full_midi');
  if (/piano solo|piano_solo|piano cover|piano_cover|piano version|piano_version|piano arrangement/.test(f)) tags.push('piano_solo');
  if (/accompaniment/.test(f)) tags.push('accompaniment');
  return tags;
}
